// Function to change language
function changeLanguage(lang) {
    // Update active language button
    document.querySelectorAll('.language-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
            // Update the main button text
            const mainBtn = document.getElementById('languageBtn');
            if (mainBtn) {
                mainBtn.innerHTML = lang.toUpperCase() + ' <i class="fas fa-chevron-down"></i>';
            }
        }
    });

    // Update content
    updateContent(lang);

    // Store language preference
    localStorage.setItem('language', lang);

    // Update URL
    updateUrlWithLanguage(lang);
}

// Initialize language switcher
document.addEventListener('DOMContentLoaded', () => {
    const languageBtn = document.getElementById('languageBtn');
    const languageDropdown = document.getElementById('languageDropdown');

    if (languageBtn && languageDropdown) {
        // Toggle dropdown visibility
        languageBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            languageDropdown.classList.toggle('show');
        });

        // Close dropdown when clicking outside
        document.addEventListener('click', (e) => {
            if (!languageBtn.contains(e.target) && !languageDropdown.contains(e.target)) {
                languageDropdown.classList.remove('show');
            }
        });

        // Add click handlers to language buttons in dropdown
        languageDropdown.querySelectorAll('button[data-lang]').forEach(btn => {
            btn.addEventListener('click', () => {
                const lang = btn.dataset.lang;
                changeLanguage(lang);
                languageDropdown.classList.remove('show');
            });
        });
    }

    // Set initial language
    const initialLang = getLanguage();
    changeLanguage(initialLang);
}); 